/* the Equal Earth projection (Šavrič, Patterson and Jenny, 2018), central meridian 0, into the box land.js is drawn in */
const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796, MM = Math.sqrt(3) / 2;
export function equalEarth(lon, lat) {
  const l = lon * Math.PI / 180, p = lat * Math.PI / 180, t = Math.asin(MM * Math.sin(p)), t2 = t * t, t6 = t2 * t2 * t2;
  return [l * Math.cos(t) / (MM * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2))), t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))];
}
export function project(box, lon, lat) { const [x, y] = equalEarth(lon, lat); return [x * box.k + box.w / 2, (box.y0 - y) * box.k]; }

// for the search box: case and accents do not matter
export const fold = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
export function search(q, list = PLACES, n = 8) {
  const f = fold(q); if (!f) return [];
  const words = f.split(' ');
  const scored = [];
  for (const p of list) {
    const name = fold(p.name), all = name + ' ' + fold(p.where);
    if (!words.every(w => all.includes(w))) continue;
    scored.push([name.startsWith(f) ? 0 : name.split(' ').some(w => w.startsWith(words[0])) ? 1 : 2, VISION_BY[p.id] ? 0 : 1, p]);
  }
  // the best match first, the places of the vision first among equals, then by name
  return scored.sort((a, b) => a[0] - b[0] || a[1] - b[1] || a[2].name.localeCompare(b[2].name)).slice(0, n).map(x => x[2]);
}
